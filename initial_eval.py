#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import random
from numbers import Integral
from pathlib import Path
from typing import Any

import numpy as np
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer
import pandas as pd
import warnings


DEFAULT_LABEL_MAP: dict[int, str] = {
    # legacy parquet mapping (used previously in this repo): -1 -> E, 0 -> N, 1 -> C
    -1: "E",
    0: "N",
    1: "C",
}

# preferred/new parquet mapping (user convention): 0 -> entailment, 1 -> contradiction, 2 -> neutral
PREFERRED_NUMERIC_MAP: dict[int, str] = {0: "E", 1: "C", 2: "N"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run deterministic initial LLM eval on CommitmentBank prompt JSON.")
    parser.add_argument("--model", required=True, help="HF model id or local model path.")
    parser.add_argument(
        "--input-json",
        type=Path,
        default=Path("data/nli_prompt_json/test-00000-of-00001.json"),
        help="Path to JSON array generated by scripts/build_nli_prompt_dataset.sh.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/initial_eval"),
        help="Directory where predictions and summary will be written.",
    )
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument(
        "--max-new-tokens",
        type=int,
        default=2,
        help="Very small generation cap to force short label outputs.",
    )
    parser.add_argument("--max-samples", type=int, default=None)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--cache-root", type=Path, default=None)
    parser.add_argument(
        "--device",
        choices=["auto", "cuda", "cpu"],
        default="auto",
        help="Execution device. auto prefers CUDA if available.",
    )
    return parser.parse_args()


def set_determinism(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)

    torch.use_deterministic_algorithms(True, warn_only=True)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def resolve_device(device: str) -> torch.device:
    if device == "cpu":
        return torch.device("cpu")
    if device == "cuda":
        if not torch.cuda.is_available():
            raise RuntimeError("Requested --device cuda but CUDA is unavailable.")
        return torch.device("cuda")
    return torch.device("cuda" if torch.cuda.is_available() else "cpu")


def load_items(path: Path, max_samples: int | None) -> list[dict[str, Any]]:
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)

    if not isinstance(data, list):
        raise ValueError(f"Expected JSON array in {path}, found: {type(data)}")

    if max_samples is not None:
        return data[:max_samples]
    return data


def load_parquet_labels_for_json(input_json: Path) -> tuple[dict[int, int] | None, dict[int, str] | None]:
    """If a parquet file matching the input JSON exists in `data/`, load its numeric labels.

    Returns (idx_to_label_map, numeric_map) where idx_to_label_map maps `idx` -> numeric label,
    and numeric_map is the mapping from numeric codes to letter labels detected/preferred.
    If no parquet is found or labels cannot be read, returns (None, None).
    """
    # expect parquet in data/ with same stem as the json file
    parquet_path = input_json.resolve().parents[1] / (input_json.stem + ".parquet")
    if not parquet_path.exists():
        return None, None

    try:
        df = read_parquet_file(parquet_path)
    except Exception:
        return None, None

    if "label" not in df.columns:
        return None, None

    # build mapping from idx to numeric label if idx column exists, otherwise by position
    if "idx" in df.columns:
        idx_to_label = {int(r["idx"]): int(r["label"]) for _, r in df.iterrows()}
    else:
        # assume order matches JSON ordering; map by row number
        idx_to_label = {i: int(l) for i, l in enumerate(df["label"].tolist())}

    # detect numeric label convention (legacy -1/0/1 or preferred 0/1/2)
    unique = set(int(x) for x in df["label"].tolist() if pd.notna(x))
    if unique.issubset({-1, 0, 1}):
        numeric_map = {-1: "E", 0: "N", 1: "C"}
    else:
        numeric_map = {0: "E", 1: "C", 2: "N"}

    return idx_to_label, numeric_map


def read_parquet_file(path: Path) -> pd.DataFrame:
    """Robustly read a parquet file into a DataFrame.

    Tries: pandas with pyarrow, pandas default, pyarrow.parquet, fastparquet.
    Raises a helpful exception if none available.
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Parquet file not found: {path}")

    # 1) try pandas with explicit engine 'pyarrow'
    try:
        return pd.read_parquet(path, engine="pyarrow")
    except Exception as e1:
        warnings.warn(f"pd.read_parquet(..., engine='pyarrow') failed: {e1}")

    # 2) try pandas default
    try:
        return pd.read_parquet(path)
    except Exception as e2:
        warnings.warn(f"pd.read_parquet(...) failed: {e2}")

    # 3) try pyarrow.parquet directly
    try:
        import pyarrow.parquet as pq

        table = pq.read_table(path)
        return table.to_pandas()
    except Exception as e3:
        warnings.warn(f"pyarrow.parquet read failed: {e3}")

    # 4) try fastparquet
    try:
        import fastparquet as fp

        return fp.ParquetFile(path).to_pandas()
    except Exception as e4:
        warnings.warn(f"fastparquet read failed: {e4}")

    raise RuntimeError(
        "Unable to read parquet file. Install 'pyarrow' or 'fastparquet', or check the file format."
    )


def build_label_token_ids(tokenizer: AutoTokenizer) -> dict[str, list[int]]:
    label_token_ids: dict[str, list[int]] = {"E": [], "N": [], "C": []}
    for token_id in range(len(tokenizer)):
        decoded = tokenizer.decode([token_id], skip_special_tokens=True)
        stripped = decoded.strip()
        if stripped in label_token_ids and stripped and stripped == stripped[:1] and len(stripped) == 1:
            label_token_ids[stripped].append(token_id)

    missing = [label for label, ids in label_token_ids.items() if not ids]
    if missing:
        raise ValueError(f"Could not find single-token candidates for labels: {missing}")

    return label_token_ids


def score_labels_from_logits(next_token_logits: torch.Tensor, label_token_ids: dict[str, list[int]]) -> tuple[dict[str, float], dict[str, float]]:
    label_logits: dict[str, float] = {}
    for label in ("E", "N", "C"):
        candidate_logits = next_token_logits[label_token_ids[label]]
        label_logits[label] = float(torch.logsumexp(candidate_logits, dim=0).item())

    logits_tensor = torch.tensor([label_logits["E"], label_logits["N"], label_logits["C"]], device=next_token_logits.device)
    probabilities = torch.softmax(logits_tensor, dim=-1)
    label_probabilities = {
        "E": float(probabilities[0].item()),
        "N": float(probabilities[1].item()),
        "C": float(probabilities[2].item()),
    }
    return label_logits, label_probabilities


def normalize_gold_label(value: Any, numeric_map: dict[int, str] | None = None) -> str | None:
    """Normalize a gold label value to one of 'E','N','C'.

    Handles string labels (entailment/neutral/contradiction or 'E'/'N'/'C'),
    and numeric conventions. If `numeric_map` is provided it will be used
    for integer inputs; otherwise `DEFAULT_LABEL_MAP` is used.
    """
    if value is None:
        return None

    if isinstance(value, bool):
        return None

    # Integers: map using provided numeric_map first, then preferred, then default
    if isinstance(value, Integral):
        if numeric_map and int(value) in numeric_map:
            return numeric_map[int(value)]
        if int(value) in PREFERRED_NUMERIC_MAP:
            return PREFERRED_NUMERIC_MAP[int(value)]
        return DEFAULT_LABEL_MAP.get(int(value))

    text = str(value).strip().lower()
    if not text:
        return None
    if text in {"e", "n", "c"}:
        return text.upper()
    if text.startswith("entail"):
        return "E"
    if text.startswith("neut"):
        return "N"
    if text.startswith("contra") or text.startswith("contrad"):
        return "C"

    # numeric string fallback
    if text.isdigit():
        if numeric_map and int(text) in numeric_map:
            return numeric_map[int(text)]
        if int(text) in PREFERRED_NUMERIC_MAP:
            return PREFERRED_NUMERIC_MAP[int(text)]
        return DEFAULT_LABEL_MAP.get(int(text))
    return None


def run_eval(args: argparse.Namespace) -> dict[str, Any]:
    set_determinism(args.seed)
    device = resolve_device(args.device)
    items = load_items(args.input_json, args.max_samples)
    if not items:
        raise ValueError(f"No examples found in {args.input_json}")

    # Detect numeric label convention in the input items and choose mapping.
    numeric_labels = {row.get("label") for row in items if isinstance(row.get("label"), Integral)}
    if -1 in numeric_labels:
        numeric_map = DEFAULT_LABEL_MAP
    else:
        # prefer the 0->E,1->C,2->N convention unless legacy -1 detected
        numeric_map = PREFERRED_NUMERIC_MAP

    cache_dir = str(args.cache_root) if args.cache_root else None
    tokenizer = AutoTokenizer.from_pretrained(args.model, cache_dir=cache_dir)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    label_token_ids = build_label_token_ids(tokenizer)

    torch_dtype = torch.float16 if device.type == "cuda" else torch.float32
    model = AutoModelForCausalLM.from_pretrained(
        args.model,
        cache_dir=cache_dir,
        torch_dtype=torch_dtype,
    )
    model.to(device)
    model.eval()

    predictions: list[dict[str, Any]] = []
    total = len(items)

    for start in range(0, total, args.batch_size):
        batch = items[start : start + args.batch_size]
        prompts = [str(row.get("llm_prompt", "")).strip() for row in batch]

        tokenized = tokenizer(
            prompts,
            return_tensors="pt",
            padding=True,
            truncation=True,
        )
        tokenized = {k: v.to(device) for k, v in tokenized.items()}

        with torch.no_grad():
            outputs = model(**tokenized)

        attention_mask = tokenized["attention_mask"]
        last_indices = attention_mask.long().sum(dim=1) - 1
        batch_indices = torch.arange(len(batch), device=device)
        next_token_logits = outputs.logits[batch_indices, last_indices, :]

        for row_idx, row in enumerate(batch):
            label_logits, distribution = score_labels_from_logits(next_token_logits[row_idx], label_token_ids)
            pred_label = max(distribution, key=distribution.get)
            gold_label = normalize_gold_label(row.get("label"), numeric_map=numeric_map)
            is_correct = bool(pred_label and gold_label and pred_label == gold_label)

            enriched = dict(row)
            enriched["prediction"] = pred_label
            enriched["label_logits"] = label_logits
            enriched["label_probabilities"] = distribution
            enriched["gold_label"] = gold_label
            enriched["is_correct"] = is_correct
            predictions.append(enriched)

    known_gold = [p for p in predictions if p["gold_label"] is not None]
    correct = sum(1 for p in known_gold if p["is_correct"])
    unknown_pred = sum(1 for p in predictions if p["prediction"] is None)

    accuracy = (correct / len(known_gold)) if known_gold else 0.0
    label_counts = {
        "E": sum(1 for p in predictions if p["prediction"] == "E"),
        "N": sum(1 for p in predictions if p["prediction"] == "N"),
        "C": sum(1 for p in predictions if p["prediction"] == "C"),
        "UNKNOWN": unknown_pred,
    }

    args.output_dir.mkdir(parents=True, exist_ok=True)
    pred_path = args.output_dir / "predictions.json"
    summary_path = args.output_dir / "summary.json"

    with pred_path.open("w", encoding="utf-8") as handle:
        json.dump(predictions, handle, ensure_ascii=False, indent=2)
        handle.write("\n")

    summary = {
        "model": args.model,
        "input_json": str(args.input_json),
        "num_examples": len(predictions),
        "num_with_gold": len(known_gold),
        "accuracy": accuracy,
        "unknown_prediction_count": unknown_pred,
        "prediction_counts": label_counts,
        "max_new_tokens": args.max_new_tokens,
        "batch_size": args.batch_size,
        "seed": args.seed,
        "device": str(device),
        "predictions_file": str(pred_path),
    }

    with summary_path.open("w", encoding="utf-8") as handle:
        json.dump(summary, handle, ensure_ascii=False, indent=2)
        handle.write("\n")

    return summary


def main() -> int:
    args = parse_args()
    summary = run_eval(args)

    print(f"Wrote predictions to {args.output_dir / 'predictions.json'}")
    print(f"Wrote summary to {args.output_dir / 'summary.json'}")
    print(f"Accuracy: {summary['accuracy']:.4f} over {summary['num_with_gold']} labeled items")
    print(f"Unknown predictions: {summary['unknown_prediction_count']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
